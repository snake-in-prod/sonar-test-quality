package io.github.snakeinprod.testquality.sensor;

import io.github.snakeinprod.testquality.lang.LanguageSupport;
import io.github.snakeinprod.testquality.lang.Languages;
import io.github.snakeinprod.testquality.model.Outline;
import io.github.snakeinprod.testquality.model.TestFile;
import io.github.snakeinprod.testquality.parse.ParsedFile;
import io.github.snakeinprod.testquality.parse.Token;
import io.github.snakeinprod.testquality.rules.RuleCatalog;
import io.github.snakeinprod.testquality.rules.RuleContext;
import io.github.snakeinprod.testquality.rules.SourceRule;
import io.github.snakeinprod.testquality.rules.TestRule;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.function.BiPredicate;
import java.util.function.Function;
import java.util.regex.Pattern;

/**
 * Runs parsing, test extraction and the active rules on one file at a time. Shared by the sensor, the command line
 * scanner and the tests, so that all three see the same results.
 */
public final class Analyzer {

  /** An issue; lines 1-based, columns 0-based, {@code endColumn} exclusive. */
  public record Issue(String path, String language, String rule, int line, int column, int endLine, int endColumn, String message) {
  }

  public record Result(String path, String language, ParsedFile file, TestFile tests, List<Issue> issues) {
  }

  /** A source file: {@code reached} when a test imports it or imports a source file that imports it. */
  public record SourceResult(String path, String language, ParsedFile file, boolean reached, List<Issue> issues) {
  }

  /** The project's other files, for rules that read the code under test. */
  public interface Project {
    /** Paths relative to the base directory of every file in this language family. */
    Set<String> paths(String family);

    /** Content of a file under the base directory (a project file, or another one such as pubspec.yaml), or null. */
    String read(String path);

    /** SonarQube language key of a project file, or null. */
    String language(String path);
  }

  private final List<LanguageSupport> supports;
  private final Project project;
  private final Map<String, Map<String, TestRule>> rules = new HashMap<>();
  private final Map<String, ParsedFile> parsed = new HashMap<>();
  private final Set<String> unparsable = new HashSet<>();
  private final Map<String, Object> shared = new HashMap<>();
  private final Map<String, Set<String>> familyPaths = new HashMap<>();
  private final Set<String> testFiles = new HashSet<>();
  private final Set<String> testImports = new HashSet<>();
  private Set<String> reached;

  /** Not source files for the test reach: generated, configuration, migrations, declarations, entry points. */
  private static final Pattern NOT_SOURCE = Pattern.compile(
    "(.*/)?(migrations|alembic|__generated__|generated|__mocks__|node_modules|dist|build|coverage|\\.dart_tool)/.*"
      + "|(.*/)?(setup|conftest|manage|noxfile|fabfile|settings|conf|wsgi|asgi|__main__)\\.py"
      + "|.*_pb2(_grpc)?\\.py|.*\\.d\\.[cm]?ts|.*\\.min\\.js|.*\\.(config|stories)\\.[cm]?[jt]sx?|(.*/)?\\.[^/]*"
      + "|(.*/)?(main|firebase_options|generated_plugin_registrant)\\.dart"
      + "|.*\\.(g|freezed|mocks|gr|config|pb|pbenum|pbjson|pbserver|pbgrpc)\\.dart");
  private static final Pattern GENERATED = Pattern.compile("(?i)@generated|do not (edit|modify)|auto-?generated|generated by");

  /**
   * @param active (family, rule key) is active in the profile
   */
  public Analyzer(List<LanguageSupport> supports, BiPredicate<String, String> active, Project project) {
    this.supports = supports;
    this.project = project;
    for (RuleCatalog.Spec spec : RuleCatalog.ALL) {
      if (active.test(spec.family(), spec.key())) {
        rules.computeIfAbsent(spec.family(), f -> new LinkedHashMap<>()).put(spec.key(), spec.factory().get());
      }
    }
  }

  public static Analyzer all(Project project) {
    return new Analyzer(Languages.create(), (f, k) -> true, project);
  }

  /** Analyses one file. Throws only on an internal error of a parser or rule; callers skip the file then. */
  public Result analyze(String path, String language, String source) {
    LanguageSupport support = Languages.forLanguage(supports, language);
    if (support == null) {
      return new Result(path, language, null, TestFile.EMPTY, List.of());
    }
    ParsedFile file = support.parse(path, language, source);
    TestFile tests = support.extract(file);
    List<Issue> issues = new ArrayList<>();
    Set<Integer> nosonar = nosonar(file);
    for (Map.Entry<String, TestRule> e : rules.getOrDefault(support.family(), Map.of()).entrySet()) {
      if (!(e.getValue() instanceof SourceRule)) {
        e.getValue().check(new Context(support, file, tests, e.getKey(), issues, nosonar, null, false));
      }
    }
    testFiles.add(path);
    testImports.addAll(support.outline(file, paths(support.family()), project::read).imports());
    reached = null;
    return new Result(path, language, file, tests, sorted(issues));
  }

  /**
   * Second pass, after every test file went through {@link #analyze}: the test reach and the {@link SourceRule} issues
   * of a source file. Null when the file does not count as a source file: generated, configuration, migration,
   * declaration or entry point files, and files without a function or class.
   */
  public SourceResult analyzeSource(String path, String language, String source) {
    LanguageSupport support = Languages.forLanguage(supports, language);
    if (support == null || NOT_SOURCE.matcher(path).matches()) {
      return null;
    }
    ParsedFile file = parsed.containsKey(path) ? parsed.get(path) : support.parse(path, language, source);
    if (file.comments().stream().anyMatch(c -> c.line() <= 5 && GENERATED.matcher(c.text()).find())) {
      return null;
    }
    Outline outline = support.outline(file, paths(support.family()), project::read);
    if (outline.functions().isEmpty() && outline.classes().isEmpty()) {
      return null;
    }
    boolean hit = reached().contains(path);
    List<Issue> issues = new ArrayList<>();
    Set<Integer> nosonar = nosonar(file);
    for (Map.Entry<String, TestRule> e : rules.getOrDefault(support.family(), Map.of()).entrySet()) {
      if (e.getValue() instanceof SourceRule) {
        e.getValue().check(new Context(support, file, TestFile.EMPTY, e.getKey(), issues, nosonar, outline, hit));
      }
    }
    return new SourceResult(path, language, file, hit, sorted(issues));
  }

  /** What tests import, and one level further what those source files import. */
  private Set<String> reached() {
    if (reached == null) {
      reached = new HashSet<>(testImports);
      for (String p : testImports) {
        String language = project.language(p);
        LanguageSupport s = testFiles.contains(p) || language == null ? null : Languages.forLanguage(supports, language);
        String source = s == null ? null : project.read(p);
        if (source != null) {
          try {
            reached.addAll(s.outline(s.parse(p, language, source), paths(s.family()), project::read).imports());
          } catch (RuntimeException e) {
            // an unparsable file reaches nothing further
          }
        }
      }
    }
    return reached;
  }

  private Set<String> paths(String family) {
    return familyPaths.computeIfAbsent(family, project::paths);
  }

  private static Set<Integer> nosonar(ParsedFile file) {
    Set<Integer> out = new HashSet<>();
    for (Token c : file.comments()) {
      if (c.text().contains("NOSONAR")) {
        out.add(c.line());
      }
    }
    return out;
  }

  private static List<Issue> sorted(List<Issue> issues) {
    issues.sort((a, b) -> a.line() != b.line() ? Integer.compare(a.line(), b.line()) : Integer.compare(a.column(), b.column()));
    return List.copyOf(issues);
  }

  private final class Context implements RuleContext {
    private final LanguageSupport support;
    private final ParsedFile file;
    private final TestFile tests;
    private final String rule;
    private final List<Issue> issues;
    private final Set<Integer> nosonar;
    private final Outline outline;
    private final boolean reached;

    Context(LanguageSupport support, ParsedFile file, TestFile tests, String rule, List<Issue> issues, Set<Integer> nosonar,
      Outline outline, boolean reached) {
      this.support = support;
      this.file = file;
      this.tests = tests;
      this.rule = rule;
      this.issues = issues;
      this.nosonar = nosonar;
      this.outline = outline;
      this.reached = reached;
    }

    @Override
    public Outline outline() {
      return outline;
    }

    @Override
    public boolean reached() {
      return reached;
    }

    @Override
    public ParsedFile file() {
      return file;
    }

    @Override
    public TestFile tests() {
      return tests;
    }

    @Override
    public ParsedFile project(String path) {
      if (parsed.containsKey(path)) {
        return parsed.get(path);
      }
      if (unparsable.contains(path)) {
        return null;
      }
      String source = project.read(path);
      String language = project.language(path);
      if (source == null || language == null || !support.languages().contains(language)) {
        unparsable.add(path);
        return null;
      }
      try {
        ParsedFile p = support.parse(path, language, source);
        parsed.put(path, p);
        return p;
      } catch (RuntimeException e) {
        unparsable.add(path);
        return null;
      }
    }

    @Override
    public Set<String> projectPaths() {
      return paths(support.family());
    }

    @Override
    public void report(Token from, Token to, String message) {
      if (!nosonar.contains(from.line())) {
        issues.add(new Issue(file.path(), file.language(), rule, from.line(), from.column(), to.endLine(), to.endColumn(), message));
      }
    }

    @Override
    @SuppressWarnings("unchecked")
    public <T> T shared(String key, Function<String, T> compute) {
      return (T) shared.computeIfAbsent(support.family() + ":" + key, compute);
    }
  }
}
